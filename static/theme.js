function downloadTextAsFile(filename, text) {
    const blob = new Blob([text], { type: 'text/markdown;charset=utf-8;' });
    const link = document.createElement('a');
    const url = URL.createObjectURL(blob);
    link.setAttribute('href', url);
    link.setAttribute('download', filename);
    link.style.visibility = 'hidden';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
}

function downloadElementAsReport(title, elementId, filename) {
    const el = document.getElementById(elementId);
    if (!el) {
        alert("No content available to download.");
        return;
    }
    const contentText = el.innerText || el.textContent;
    if (!contentText || contentText.trim().length === 0 || contentText.includes("Loading")) {
        alert("Content is still loading. Please try again in a moment.");
        return;
    }

    const header = `==================================================\nWELLNESSIQ - ${title.toUpperCase()}\nDate: ${new Date().toLocaleString()}\n==================================================\n\n`;
    const fullReport = header + contentText + `\n\n==================================================\nGenerated by WellnessIQ AI Engine\n==================================================\n`;
    
    downloadTextAsFile(filename || `${title.toLowerCase().replace(/\s+/g, '_')}_plan.txt`, fullReport);
}

window.downloadTextAsFile = downloadTextAsFile;
window.downloadElementAsReport = downloadElementAsReport;

